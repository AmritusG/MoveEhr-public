#!/usr/bin/env python3
"""Writes docs/PARAMS.md: every parameter each bundle shows in Arena (group, name, range, default, options), read from the
built bundles through the offline harness. usage: tools/params_doc.py   (after a Release build)"""
import os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLES = ('MoveEhr', 'MoveEhrFX', 'MoveEhrWow', 'MoveEhrWowFX')
ROW = re.compile(r'^\s*(\d+) \|([^|]*)\|([^|]*)\|[^|]*\| type\s+(\d+) \| range (\S+) \| default (\S+) \|[^|]*\|[^|]*(?:\| options (.*))?$')
KIND = {0: 'toggle', 1: 'button', 10: 'slider', 11: 'option', 12: 'audio (FFT)', 13: 'integer', 14: 'file', 100: 'text', 200: 'colour hue', 201: 'colour saturation', 202: 'colour brightness', 203: 'colour alpha'}

out = ['# Parameters', '', 'Generated by `tools/params_doc.py` from the built bundles. The index is the FFGL parameter index Arena shows.', '']
for b in BUNDLES:
    with tempfile.NamedTemporaryFile('w', suffix='.txt', delete=False) as f:
        f.write('bundle %s/build/%s.bundle\nsize 64 36\ninstance\nparams\n' % (ROOT, b))
    txt = subprocess.run([os.path.join(ROOT, 'build', 'loadehr_harness'), f.name], capture_output=True, text=True).stdout
    os.unlink(f.name)
    rows = [m.groups() for m in map(ROW.match, txt.splitlines()) if m]
    out += ['## %s (%d parameters)' % (b, len(rows)), '', '| # | Group | Name | Kind | Range | Default | Options |', '|---|---|---|---|---|---|---|']
    for i, g, n, t, r, d, o in rows:
        o = re.sub(r'(\w+) 1( / \1 \d+)+', lambda m: '%s 1 .. %s %s' % (m.group(1), m.group(1), m.group(0).rsplit(' ', 1)[1]), o or '')
        kind = KIND.get(int(t), 'type %s' % t)
        out.append('| %s | %s | %s | %s | %s | %s | %s |' % (i, g.strip(), n.strip(), kind, r if kind in ('slider', 'integer') or kind.startswith('colour') else '', d if kind in ('slider', 'integer', 'option', 'toggle') or kind.startswith('colour') else '', (o or '').strip().replace('|', '/')))
    out.append('')
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs', 'PARAMS.md'), 'w').write('\n'.join(out))
print('docs/PARAMS.md:', ', '.join(b for b in BUNDLES))
